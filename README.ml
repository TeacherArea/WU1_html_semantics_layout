# Ett första webbutvecklingsprojekt

I detta projekt skall vi lägga till olika **html-element** (innehåll) till en liten webbplats, göra den stilig med **css** (placeringar, storlekar och färger), dela upp koden i fyra olika webbsidor (**arkitektur**) och lägga till några små **javascript** (kod).

De olika självbeskrivande brancherna är tänkt att visa på utvecklingen. Det rekomenderas att följa dessa i turordning:
 1. main (denna branch)
 2. html
 3. css
 4. javascript
 6. architechture